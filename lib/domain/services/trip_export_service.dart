import '../models/balance_summary.dart';
import '../models/expense.dart';
import '../models/trip.dart';
import '../models/trip_member.dart';

class TripExportService {
  static String _resolveMemberName(List<TripMember> members, String memberOrUserId, {String fallback = 'Member'}) {
    if (memberOrUserId.isEmpty) return fallback;
    final direct = members.where((m) => m.id == memberOrUserId).firstOrNull;
    if (direct != null) return direct.displayName;
    final byUserId = members.where((m) => m.userId.isNotEmpty && m.userId == memberOrUserId).firstOrNull;
    if (byUserId != null) return byUserId.displayName;
    final merged = members.where((m) => m.mergedIntoMemberId == memberOrUserId).firstOrNull;
    return merged?.displayName ?? fallback;
  }

  /// Generates a human-readable text summary of the trip financials.
  static String generateTextSummary({
    required Trip trip,
    required List<Expense> expenses,
    required BalanceSummary balanceSummary,
  }) {
    final buffer = StringBuffer();
    final currency = trip.currencyCode;
    final totalRupees = (balanceSummary.totalTripSpentInPaise / 100).toStringAsFixed(2);

    buffer.writeln('====================================');
    buffer.writeln('${trip.emoji} ${trip.name} — Financial Summary');
    buffer.writeln('====================================');
    buffer.writeln('Status: ${trip.lifecycleState.displayName.toUpperCase()}');
    buffer.writeln('Total Spending: $currency $totalRupees');
    buffer.writeln('Total Expenses: ${expenses.length}');
    buffer.writeln('Members (${trip.members.length}): ${trip.members.map((m) => m.displayName).join(', ')}');
    buffer.writeln('');

    // Category Breakdown
    buffer.writeln('--- SPENDING BY CATEGORY ---');
    final categoryTotals = <String, int>{};
    for (final exp in expenses) {
      final cat = exp.category.name.toLowerCase();
      categoryTotals[cat] = (categoryTotals[cat] ?? 0) + exp.amountInPaise;
    }
    categoryTotals.forEach((cat, amt) {
      final catRupees = (amt / 100).toStringAsFixed(2);
      final percentage = balanceSummary.totalTripSpentInPaise > 0
          ? ((amt / balanceSummary.totalTripSpentInPaise) * 100).toStringAsFixed(1)
          : '0';
      buffer.writeln('• ${cat.toUpperCase()}: $currency $catRupees ($percentage%)');
    });
    buffer.writeln('');

    // Member Net Balances
    buffer.writeln('--- MEMBER NET BALANCES ---');
    for (final m in trip.members) {
      final netPaise = balanceSummary.memberNetBalances[m.id] ?? 0;
      final netRupees = (netPaise.abs() / 100).toStringAsFixed(2);
      if (netPaise > 0) {
        buffer.writeln('• ${m.displayName}: Gets back $currency $netRupees');
      } else if (netPaise < 0) {
        buffer.writeln('• ${m.displayName}: Owes $currency $netRupees');
      } else {
        buffer.writeln('• ${m.displayName}: Settled up ($currency 0.00)');
      }
    }
    buffer.writeln('');

    // Simplified Settlement Payments
    buffer.writeln('--- SIMPLIFIED SETTLEMENTS ---');
    if (balanceSummary.simplifiedSettlements.isEmpty) {
      buffer.writeln('All balances are fully settled!');
    } else {
      for (final s in balanceSummary.simplifiedSettlements) {
        final from = _resolveMemberName(trip.members, s.fromMemberId, fallback: 'Member');
        final to = _resolveMemberName(trip.members, s.toMemberId, fallback: 'Member');
        final amtRupees = (s.amountInPaise / 100).toStringAsFixed(2);
        buffer.writeln('• $from pays $to: $currency $amtRupees');
      }
    }

    buffer.writeln('');
    buffer.writeln('Generated by Kith Expense Splitting');
    buffer.writeln('====================================');
    return buffer.toString();
  }

  /// Generates CSV data for spreadsheets.
  static String generateCsvSummary({
    required Trip trip,
    required List<Expense> expenses,
  }) {
    final buffer = StringBuffer();
    buffer.writeln('Date,Title,Category,PaidBy,Amount,SplitType,Participants');

    for (final exp in expenses) {
      final payer = _resolveMemberName(trip.members, exp.paidById, fallback: 'Unknown');
      final amt = (exp.amountInPaise / 100).toStringAsFixed(2);
      final date = '${exp.createdAt.year}-${exp.createdAt.month.toString().padLeft(2, '0')}-${exp.createdAt.day.toString().padLeft(2, '0')}';
      final participants = exp.splits.length;

      buffer.writeln('"$date","${exp.title.replaceAll('"', '""')}","${exp.category.name}","$payer","$amt","${exp.splitType.name}","$participants"');
    }

    return buffer.toString();
  }
}
