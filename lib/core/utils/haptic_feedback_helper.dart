import 'package:flutter/services.dart';

/// Tactile micro-haptic feedback helper for rich mobile interactions.
class HapticHelper {
  HapticHelper._();

  static void light() {
    HapticFeedback.lightImpact();
  }

  static void medium() {
    HapticFeedback.mediumImpact();
  }

  static void heavy() {
    HapticFeedback.heavyImpact();
  }

  static void selection() {
    HapticFeedback.selectionClick();
  }

  static void success() {
    HapticFeedback.mediumImpact();
  }
}
